// Fetches the top tracks/artists behind the "music" section and writes them to
// src/content/spotify.generated.ts.
//
// This runs in CI just before `vite build` (see .github/workflows/deploy.yml).
// The site is static, so build time is the only place the Spotify credentials
// can live — a VITE_* variable would be inlined verbatim into the public bundle,
// and /me/top/* needs an authorization-code grant, not client credentials.
//
// Locally: mint a token with scripts/spotify-auth.mjs, then
//
//   SPOTIFY_CLIENT_ID=... SPOTIFY_CLIENT_SECRET=... SPOTIFY_REFRESH_TOKEN=... \
//     node scripts/fetch-spotify.mjs
//
// and commit the output, so builds without secrets still have real data to show.

import { writeFile } from 'node:fs/promises';

const OUT = 'src/content/spotify.generated.ts';
const TIME_RANGE = 'short_term'; // roughly the last 4 weeks
const LIMIT = 3;
const ATTEMPTS = 3;

const {
  SPOTIFY_CLIENT_ID: id,
  SPOTIFY_CLIENT_SECRET: secret,
  SPOTIFY_REFRESH_TOKEN: refreshToken,
} = process.env;

/** A credential problem needs a human. Everything else is worth retrying. */
class FatalError extends Error {}

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

/** Fetch JSON, retrying 429/5xx and network blips. Other 4xx are fatal. */
async function request(url, init, label) {
  let last;

  for (let attempt = 1; attempt <= ATTEMPTS; attempt++) {
    let res;
    try {
      res = await fetch(url, init);
    } catch (err) {
      last = new Error(`${label}: ${err.message}`);
      if (attempt < ATTEMPTS) await sleep(attempt * 1000);
      continue;
    }

    if (res.ok) return res.json();

    const body = await res.text();

    if (res.status !== 429 && res.status < 500) {
      // A revoked token comes back as 400 invalid_grant, not 401 — so key the
      // actionable hint off the error body rather than the status alone.
      const credentials =
        res.status === 401 ||
        res.status === 403 ||
        /invalid_grant|invalid_client/.test(body);
      throw new FatalError(
        `${label}: ${res.status} ${body}` +
          (credentials
            ? '\nThe credentials are invalid, revoked, or missing the user-top-read scope.' +
              ' Re-run scripts/spotify-auth.mjs and update SPOTIFY_REFRESH_TOKEN.'
            : ''),
      );
    }

    last = new Error(`${label}: ${res.status} ${body}`);
    if (attempt < ATTEMPTS) {
      const retryAfter = Number(res.headers.get('retry-after'));
      await sleep(retryAfter > 0 ? retryAfter * 1000 : attempt * 1000);
    }
  }

  throw last;
}

const accessToken = async () => {
  const { access_token: token } = await request(
    'https://accounts.spotify.com/api/token',
    {
      method: 'POST',
      headers: {
        Authorization: `Basic ${Buffer.from(`${id}:${secret}`).toString('base64')}`,
        'Content-Type': 'application/x-www-form-urlencoded',
      },
      body: new URLSearchParams({ grant_type: 'refresh_token', refresh_token: refreshToken }),
    },
    'token refresh',
  );
  return token;
};

const top = (token, type) =>
  request(
    `https://api.spotify.com/v1/me/top/${type}?time_range=${TIME_RANGE}&limit=${LIMIT}`,
    { headers: { Authorization: `Bearer ${token}` } },
    `top ${type}`,
  );

// Emitted as .ts rather than .json because tsconfig.app.json does not set
// resolveJsonModule, and this way `npm run typecheck` covers it for free.
const render = (data) => `// GENERATED by scripts/fetch-spotify.mjs — do not edit by hand.
// Refreshed on every deploy and by the daily cron in .github/workflows/deploy.yml.
// Committed so a build without Spotify credentials still has data to show.
export const spotifyTop = ${JSON.stringify(data, null, 2)};
`;

async function main() {
  if (!refreshToken) {
    console.log(`No SPOTIFY_REFRESH_TOKEN set — keeping the committed ${OUT}.`);
    return;
  }
  if (!id || !secret) {
    throw new FatalError('SPOTIFY_REFRESH_TOKEN is set but SPOTIFY_CLIENT_ID/SECRET are not.');
  }

  const token = await accessToken();
  const [tracks, artists] = await Promise.all([top(token, 'tracks'), top(token, 'artists')]);

  // Keep only the fields the UI renders. Spotify's raw track objects each carry
  // a ~180-entry available_markets array and a full album payload.
  const data = {
    updatedAt: new Date().toISOString().slice(0, 10),
    tracks: tracks.items.map((t) => ({
      name: t.name,
      artist: t.artists.map((a) => a.name).join(', '),
      url: t.external_urls.spotify,
    })),
    artists: artists.items.map((a) => ({ name: a.name, url: a.external_urls.spotify })),
  };

  await writeFile(OUT, render(data));
  console.log(`Wrote ${OUT} — ${data.tracks.length} tracks, ${data.artists.length} artists.`);
}

main().catch((err) => {
  if (err instanceof FatalError) {
    console.error(`::error::${err.message}`);
    process.exit(1);
  }
  // Spotify being briefly unreachable shouldn't block an unrelated content
  // deploy — fall back to whatever snapshot is already committed.
  console.error(`::warning::Spotify fetch failed, keeping the committed ${OUT}. ${err.message}`);
});
